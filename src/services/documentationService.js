/**
 * DevProbe — API Documentation Generator Service
 * Day 15: API Documentation Generator & Collection Import/Export
 *
 * Provides functions for generating professional, structured API documentation
 * from saved collections and requests in GitHub-Flavored Markdown and standalone HTML5.
 * Also generates accurate, shell-escaped cURL command snippets and extracts sample
 * responses from execution history without exposing sensitive credentials.
 *
 * CREDENTIAL SAFETY & REDACTION POLICY:
 *
 * 1. Reliably Detectable Credentials (Strictly Redacted / Omitted):
 *    - Host AES-256-GCM Ciphertext Tokens: Tokens matching 'enc:v1:<iv>:<tag>:<ciphertext>'
 *      are unambiguous local encryption signatures generated by DevProbe. They are
 *      host-specific secrets and are replaced with '[REDACTED_SECRET]' in cURL commands,
 *      request bodies, and sample response bodies.
 *    - URL Authority Credentials: Embedded 'user:password@' in URLs are defined by
 *      RFC 3986 and are stripped cleanly using standard WHATWG URL parsing.
 *    - Standard Sensitive Request Headers: 'Authorization', 'Cookie', 'Set-Cookie',
 *      'X-Api-Key', 'Proxy-Authorization', 'X-Auth-Token' (RFC 7230 token names) are
 *      unambiguously identified via SENSITIVE_HEADERS and omitted from documentation.
 *    - Standard Sensitive Response Headers: 'Set-Cookie' (and other session identifiers)
 *      are filtered via SENSITIVE_RESPONSE_HEADERS.
 *
 * 2. Arbitrary Application Data (Preserved Without Overly Broad Redaction):
 *    - Legitimate Response Bodies: Real-world APIs return fields like {"token_type": "Bearer",
 *      "expires_in": 3600, "status": "active"}. Heuristic regex search-and-replace for words
 *      like "token", "key", or "secret" would corrupt legitimate documentation examples.
 *    - Request Bodies & Template Variables: Variables like '{{password}}' or '{{auth_token}}'
 *      are legitimate template definitions and must not be mangled.
 *    - Error Messages in Responses: Messages such as "Invalid API key" or "Password required"
 *      are legitimate response contents and are preserved intact.
 */

