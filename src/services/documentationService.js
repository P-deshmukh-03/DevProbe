/**
 * Generates structured GitHub-Flavored Markdown documentation for a collection specified by ID.
 * Retrieves collection metadata, associated saved requests, and latest sample responses.
 *
 * @param {number|string} collectionId - The collection ID
 * @returns {Promise<{ collection: object, requests: Array<object>, markdown: string }>}
 */
async function getCollectionMarkdown(collectionId) {
  const numericId = parseInt(collectionId, 10);
  if (Number.isNaN(numericId) || numericId <= 0) {
    throw new AppError('Collection ID must be a positive integer', 400, 'INVALID_COLLECTION_ID', null, 'collectionId');
  }

  const collection = await collectionService.getCollectionById(numericId);
  if (!collection) {
    throw new AppError(`Collection with ID ${numericId} not found`, 404, 'NOT_FOUND');
  }

  const requests = await savedRequestService.getSavedRequests({ collectionId: numericId });
  const sampleResponses = await getSampleResponsesForRequests(requests);
  const markdown = generateCollectionMarkdown(collection, requests, sampleResponses);

  return { collection, requests, markdown };
}

